"""Write docs/HINDI_STRINGS.md: every UI string, English and Hindi side by side, for review."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
I18N = ROOT / "frontend" / "src" / "i18n"
OUT = ROOT / "docs" / "HINDI_STRINGS.md"


def _flat(d: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(_flat(v, f"{prefix}{k}."))
        else:
            out[f"{prefix}{k}"] = str(v)
    return out


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    en = _flat(json.loads((I18N / "en.json").read_text()))
    hi = _flat(json.loads((I18N / "hi.json").read_text()))
    hi.pop("_draft", None)
    groups: dict[str, list[str]] = {}
    for key in en:
        groups.setdefault(key.split(".")[0], []).append(key)
    lines = [
        "# Hindi review table",
        "",
        "Generated by `backend/scripts/hindi_table.py` from `frontend/src/i18n/en.json` and",
        "`hi.json`.",
        f"{len(en)} strings. Hindi is DRAFT except `app.*`, `health.*`, `lang.*`.",
        "Edit `hi.json`, not this file.",
        "`{{x}}` is a value filled in by the page.",
        "",
    ]
    for g, keys in groups.items():
        lines += [f"## {g} ({len(keys)})", "", "| Key | English | Hindi |", "|---|---|---|"]
        lines += [f"| `{k}` | {_cell(en[k])} | {_cell(hi.get(k, '**MISSING**'))} |" for k in keys]
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{len(en)} strings, {len(groups)} groups -> {OUT}")


if __name__ == "__main__":
    main()
